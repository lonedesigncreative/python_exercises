# Variable declarations
integer_number = 25              # Integer variable (int)
decimal_number = 3.14            # Decimal variable (float)
text_example = "Hello, world!"   # Text variable (string)

# Printing the values combining text + variables
print("The integer value is:", integer_number)     # Shows the integer value
print("The decimal value is:", decimal_number)     # Shows the decimal value
print("The stored text is:", text_example)         # Shows the text