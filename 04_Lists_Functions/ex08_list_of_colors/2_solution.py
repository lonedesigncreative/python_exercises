# initial list
colors = ["yellow", "blue", "white", "black", "green"]

# print full list
print(colors)

# print index 2
print(colors[2])

# change index 0
colors[0] = "red"

# print updated list
print(colors)

# append new color
colors.append("yellow")

# print updated list
print(colors)

# insert at index 2
colors.insert(2, "purple")

# print updated list
print(colors)

# remove last element
colors.pop()

# print updated list
print(colors)

# print list size
print(len(colors))