# Create a function to calculate the average of three grades
def Calculate_Average_Grades(grade1, grade2, grade3):
    average = (grade1 + grade2 + grade3) / 3
    print(f"The average of the three grades is: {average}")

# Main program
Calculate_Average_Grades(20, 12, 16)
Calculate_Average_Grades(10, 15, 9)
Calculate_Average_Grades(15, 11, 8)